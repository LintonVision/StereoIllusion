%-------------------------------------------------------------------------------
% RADIUS
%-------------------------------------------------------------------------------

radius = 5.5;

%-------------------------------------------------------------------------------
% CIRCLE RADIUS 1
%-------------------------------------------------------------------------------

% Define the number of points to use to draw the circle
nPoints = 200;

% Define the angles for the points on the circle
theta = linspace(0, 2*pi, nPoints);

% Calculate the x and y coordinates of the points on the circle
x = cos(theta);
y = sin(theta);

% Concatenate the x and y coordinates into a 2 x nPoints matrix
circle = [x; y];
circle = repelem(circle,1,2);
circle = [circle, circle(:,1)];
circle(:,1) = [];

%-------------------------------------------------------------------------------
% BACK CIRCLE
%-------------------------------------------------------------------------------

backCircle = radius*circle;

%-------------------------------------------------------------------------------
% FRONT CIRCLE
%-------------------------------------------------------------------------------

frontCircle = 0.5*backCircle;

%-------------------------------------------------------------------------------
% BACK RING
%-------------------------------------------------------------------------------

ring = 0.95*circle;
ring = [circle, ring];
backRing = radius*ring;

%-------------------------------------------------------------------------------
% FRONT RING
%-------------------------------------------------------------------------------
ring = 0.9*circle;
ring = [circle, ring];
frontRing = 0.5*radius*ring;

%-------------------------------------------------------------------------------
% SQUARE RADIUS 1
%-------------------------------------------------------------------------------

% Define the number of dots
nDots = 5000;

Dots = ones(nDots,2);

for i = 1:nDots
  
  Dots(i,1) = (Dots(i,1)*rand - 0.5) * 2;
  Dots(i,2) = (Dots(i,2)*rand - 0.5) * 2;
 
end 
%

%-------------------------------------------------------------------------------
% CIRCLE RADIUS 1
%-------------------------------------------------------------------------------

array = Dots(:,1).^2 + Dots(:,2).^2;

indicies = array < 1;

Dots = Dots(indicies,:);

%-------------------------------------------------------------------------------
% BACK CIRCLE
%-------------------------------------------------------------------------------

backDots = radius*Dots;

%-------------------------------------------------------------------------------
% CIRCLE RADIUS 0.5
%-------------------------------------------------------------------------------

array = Dots(:,1).^2 + Dots(:,2).^2;

indicies = array < (0.5^2);

Dots = Dots(indicies,:);

%-------------------------------------------------------------------------------
% FRONT CIRCLE
%-------------------------------------------------------------------------------

frontDots = radius*Dots;

